    def test_default_output_cannot_replace_an_active_run(self):
        ready = Path(self.temporary.name) / "ready"
        release = Path(self.temporary.name) / "release"
        (self.validation / "validate_wait.py").write_text(
            "from pathlib import Path\nimport time\n"
            f"Path({str(ready)!r}).touch()\n"
            f"while not Path({str(release)!r}).exists():\n    time.sleep(0.01)\n"
            "print('COMPLETED_OK')\n"
        )
        destination = self.project / ".test-results/validation/latest"
        process = subprocess.Popen(
            [sys.executable, str(RUNNER), "--project", str(self.project), "--no-color"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        )
        try:
            deadline = time.monotonic() + 5
            while not ready.exists() and time.monotonic() < deadline:
                time.sleep(0.02)
            self.assertTrue(ready.exists(), "First run did not reach its validator")
            self.assertTrue((destination / "report.json").is_file(), "Active report is not at its fixed path")
            before = (destination / "report.json").read_bytes()
            second = self.invoke(timeout=5)
            self.assertEqual(second.returncode, 2, second.stdout + second.stderr)
            self.assertIn("already writing", second.stderr)
            self.assertEqual((destination / "report.json").read_bytes(), before)
            release.touch()
            stdout, stderr = process.communicate(timeout=5)
            self.assertEqual(process.returncode, 0, stdout + stderr)
            self.assertTrue(json.loads((destination / "report.json").read_text())["complete"])
        finally:
            release.touch()
            if process.poll() is None:
                process.send_signal(signal.SIGTERM)
            process.communicate(timeout=6)

    def test_report_artifacts_are_git_ignored_at_default_and_custom_paths(self):
        subprocess.run(["git", "init", "-q", str(self.project)], check=True)
        (self.validation / "validate_example.py").write_text("print('OK')\n")
        custom = self.project / "reports/custom"
        for arguments, destination in (((), self.project / ".test-results/validation/latest"),
                                       (("--report-dir", str(custom)), custom)):
            with self.subTest(destination=destination):
                result = self.invoke(*arguments)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                artifacts = [p.relative_to(self.project).as_posix() for base in
                             (self.project / ".test-results/validation", custom) if base.exists()
                             for p in base.rglob("*") if p.is_file()]
                check = subprocess.run(["git", "check-ignore", "--stdin"], cwd=self.project,
                                       input="\n".join(artifacts) + "\n", text=True, capture_output=True)
                self.assertEqual(set(check.stdout.splitlines()), set(artifacts), check.stderr)
                self.assertNotEqual(subprocess.run(["git", "check-ignore", "tests/validation/validate_example.py"],
                                                   cwd=self.project, capture_output=True).returncode, 0)
        before = (custom / "report.json").read_bytes()
        repeated = self.invoke("--report-dir", str(custom))
        self.assertEqual(repeated.returncode, 2, "Explicit saved evidence must not be overwritten")
        self.assertEqual((custom / "report.json").read_bytes(), before)


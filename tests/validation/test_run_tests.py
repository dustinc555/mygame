    @unittest.skipUnless(sys.platform.startswith("linux"), "Linux process-state inspection")
    def test_cancellation_allows_nested_process_cleanup_after_leader_exits(self):
        marker = Path(self.temporary.name) / "leaf.pid"
        coordinator = self.validation / "coordinator.py"
        coordinator.write_text(
            "import os, signal, subprocess, sys, time\nfrom pathlib import Path\n"
            "stopping = False\n"
            "def stop(*_):\n    global stopping\n    stopping = True\n"
            "signal.signal(signal.SIGTERM, stop)\n"
            "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(30)'], start_new_session=True)\n"
            f"Path({str(marker)!r}).write_text(str(child.pid))\n"
            "while not stopping:\n    time.sleep(0.01)\n"
            "time.sleep(0.15)\n"
            "os.killpg(child.pid, signal.SIGTERM)\nchild.wait(timeout=2)\n"
        )
        path = "tests/validation/validate_outer.py"
        (self.project / path).write_text(
            "import subprocess, sys, time\n"
            f"subprocess.Popen([sys.executable, {str(coordinator)!r}])\n"
            "time.sleep(30)\n"
        )
        cancelled = Event()
        leaf_pid = None
        try:
            with ThreadPoolExecutor(max_workers=1) as pool:
                future = pool.submit(runner.run_test, runner.Test(path, "python", path, timeout=5),
                                     self.project, Path(self.temporary.name) / "results", "unused", cancelled)
                deadline = time.monotonic() + 3
                while not marker.exists() and time.monotonic() < deadline:
                    time.sleep(0.01)
                self.assertTrue(marker.exists(), "Nested child never became ready")
                leaf_pid = int(marker.read_text())
                cancelled.set()
                row = future.result(timeout=5)
            self.assertEqual(row["status"], "interrupted")
            state = Path(f"/proc/{leaf_pid}/stat")
            self.assertTrue(not state.exists() or state.read_text().split()[2] == "Z",
                            "Nested child remained alive after cancellation returned")
        finally:
            cancelled.set()
            if leaf_pid is not None:
                try:
                    os.killpg(leaf_pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass



    def test_default_report_replaces_one_fixed_directory_and_reruns_failures(self):
        bad = self.validation / "validate_bad.py"
        bad.write_text("print('FIRST_FAILURE')\nraise SystemExit(1)\n")
        (self.validation / "validate_good.py").write_text("print('GOOD_OK')\n")
        destination = self.project / ".test-results/validation/latest"
        first = self.invoke()
        self.assertEqual(first.returncode, 1, first.stdout + first.stderr)
        self.assertTrue((destination / "index.html").is_file(), "Default report needs a stable location")
        original = json.loads((destination / "report.json").read_text())
        self.assertEqual(original["counts"], {"failed": 1, "passed": 1})
        old_good = next(row for row in original["results"] if row["status"] == "passed")
        (destination / "stale-artifact.txt").write_text("must not accumulate")
        bad.write_text("print('NOW_OK')\n")
        second = self.invoke("--rerun-failed")
        self.assertEqual(second.returncode, 0, second.stdout + second.stderr)
        report = json.loads((destination / "report.json").read_text())
        self.assertEqual(report["counts"], {"passed": 1})
        self.assertEqual(report["scope"]["paths"], ["tests/validation/validate_bad.py"])
        self.assertFalse(report["scope"]["full_suite"])
        self.assertFalse((destination / "stale-artifact.txt").exists())
        self.assertFalse((destination / old_good["log"]).exists(), "Previous logs must not accumulate")
        self.assertEqual(len((destination / "results.jsonl").read_text().splitlines()), 1)
        self.assertIn("NOW_OK", (destination / report["results"][0]["log"]).read_text())
        self.assertEqual([p.name for p in destination.parent.iterdir() if p.is_dir()], ["latest"])
        self.assertIn(str(destination / "index.html"), second.stdout)


    def test_timeout_is_reported_and_descendants_are_stopped(self):
        (self.validation / "validate_slow.py").write_text(
            "import subprocess, sys, time\n"
            "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(30)'])\n"
            "print('CHILD_PID', child.pid, flush=True)\n"
            "time.sleep(30)\n"
        )
        destination = Path(self.temporary.name) / "results"
        result = self.invoke("--timeout", "0.3", "--report-dir", str(destination))
        self.assertEqual(result.returncode, 1, result.stderr)
        report = json.loads((destination / "report.json").read_text())
        self.assertEqual(report["counts"], {"timeout": 1})
        log = (destination / report["results"][0]["log"]).read_text()
        child_pid = int(log.split("CHILD_PID ")[1].splitlines()[0])
        if sys.platform.startswith("linux"):
            state = Path(f"/proc/{child_pid}/stat")
            for _ in range(20):
                if not state.exists() or state.read_text().split()[2] == "Z":
                    break
                time.sleep(0.05)
            else:
                os.kill(child_pid, 9)
                self.fail("Timeout left a live descendant behind")

